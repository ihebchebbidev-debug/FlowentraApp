CREATE VIEW "v_AuthIssuesRecent" TABLESPACE public AS (SELECT "UserId", "Reason", count(*) AS "AttemptCount", sum( CASE WHEN "Success" = true THEN 1 ELSE 0 END) AS "Successes", sum( CASE WHEN "Success" = false THEN 1 ELSE 0 END) AS "Failures", max("Timestamp") AS "LastAttempt", array_agg(DISTINCT "ErrorMessage" ORDER BY "ErrorMessage") AS "Errors" FROM "TokenRefreshLog" WHERE "Timestamp" > (CURRENT_TIMESTAMP - '24:00:00'::interval) GROUP BY "UserId", "Reason" ORDER BY (max("Timestamp")) DESC);
CREATE VIEW "v_RecentSyncFailures" TABLESPACE public AS (SELECT "DeviceId", "EntityType", "Status", count(*) AS "FailureCount", max("Timestamp") AS "LastFailure", array_agg(DISTINCT "ErrorMessage" ORDER BY "ErrorMessage") AS "ErrorMessages" FROM "SyncFailureLog" WHERE "Resolved" = false AND "Timestamp" > (CURRENT_TIMESTAMP - '24:00:00'::interval) GROUP BY "DeviceId", "EntityType", "Status" ORDER BY (max("Timestamp")) DESC);
CREATE VIEW "v_SyncPerformanceStats" TABLESPACE public AS (SELECT date_trunc('hour'::text, "Timestamp") AS "Hour", count(*) AS "SyncAttempts", avg("SyncDuration")::bigint AS "AvgDuration", max("SyncDuration") AS "MaxDuration", min("SyncDuration") AS "MinDuration", avg("OperationsSucceeded") AS "AvgOpsSucceeded", avg("OperationsFailed") AS "AvgOpsFailed", sum( CASE WHEN "OperationsFailed" > 0 THEN 1 ELSE 0 END) AS "FailedSyncs", round(100.0 * sum( CASE WHEN "OperationsFailed" = 0 THEN 1 ELSE 0 END)::numeric / count(*)::numeric, 2) AS "SuccessRate" FROM "SyncPerformanceLog" WHERE "Timestamp" > (CURRENT_TIMESTAMP - '7 days'::interval) GROUP BY (date_trunc('hour'::text, "Timestamp")) ORDER BY (date_trunc('hour'::text, "Timestamp")) DESC);